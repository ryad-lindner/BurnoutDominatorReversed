"""Compiles the project's paraLLEl-GS shaders into SPIR-V headers in ps2xRuntime/src/lib/gs/shaders:
pgs_sample_circuit.frag into pgs_sample_circuit.spv.h, and the pinned checkout's triangle_setup.comp
and single_sample_heuristic.comp, with the menu smoothing changes below, into
pgs_triangle_setup.spv.h and pgs_single_sample_heuristic.spv.h.

usage: python tools/pgs_shader.py --glslang <glslangValidator> --pgs <paraLLEl-GS checkout>

glslangValidator builds from the checkout's Granite/third_party/glslang (target
glslang-standalone). The headers are committed, so building the game does not need it. The
changed shaders' headers name their sources and hash them; cmake/ParallelGSPatches.cmake stops
when the checkout's sources no longer match, so a paraLLEl-GS update cannot pair them with
bindings and structures they were not built for.
"""
import argparse
import hashlib
import pathlib
import re
import subprocess
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
SHADERS = ROOT / "ps2xRuntime" / "src" / "lib" / "gs" / "shaders"

# Menu smoothing. Flat triangles (no perspective, one Z) are taken for UI and interpolated once
# a pixel, so at 2x and 4x every sample of a pixel reads the same texel. Those that
# gs_interface.cpp marks with bit 27 of the texture word (palette textures with LINEAR
# magnification, while bdr_smooth_ui_sprites is set: see cmake/ParallelGSPatches.cmake)
# interpolate per sample. The single-sample heuristic still counts them as 3D where UI shares
# their vertices, so that both sides of an edge rasterize alike, but leaves them out of the
# pass's 3D depth range and of "the pass has 3D", which decide the demotion of other UI.
PATCHED = {
    "triangle_setup": [
        ("        bool should_interpolate_per_sample = multisample;\n",
         "        bool should_interpolate_per_sample = multisample || (primitive_attr.data[index].tex & (1u << 27)) != 0;\n", 1),
    ],
    "single_sample_heuristic": [
        ("void mark_full_3d(uint z, uint zlo, uint zhi)\n{\n    atomicMin(PassFull3DMinZ, z);\n    atomicMax(PassFull3DMaxZ, z);\n",
         "void mark_full_3d(uint z, uint zlo, uint zhi, bool in_3d_range)\n{\n    if (in_3d_range)\n    {\n"
         "        atomicMin(PassFull3DMinZ, z);\n        atomicMax(PassFull3DMaxZ, z);\n    }\n", 1),
        ("    atomicExchange(HasAnyFull3D, 1u);\n",
         "    if (in_3d_range)\n        atomicExchange(HasAnyFull3D, 1u);\n", 1),
    ] + [
        ("mark_full_3d(vertex_position.data[3 * i + %d].z, zlo, zhi);" % v,
         "mark_full_3d(vertex_position.data[3 * i + %d].z, zlo, zhi, (primitive_attr.data[i].tex & (1u << 27)) == 0);" % v, 1)
        for v in range(3)
    ],
}


def read_source(path):
    return path.read_text(encoding="utf-8").replace("\r\n", "\n")


def sources(shaders, name):
    """The shader file and the headers it includes, in order, all from the checkout's shader directory."""
    found = []

    def visit(file):
        if file in found:
            return
        assert (shaders / file).exists(), "%s is not in gs/shaders: hash it too" % file
        found.append(file)
        for include in re.findall(r'^#include "([^"]+)"', read_source(shaders / file), re.M):
            visit(include)

    visit(name)
    return found


def compile_spirv(glslang, pgs, source, options):
    with tempfile.TemporaryDirectory() as scratch:
        spv = pathlib.Path(scratch) / "out.spv"
        subprocess.run([glslang, "-V", "--target-env", "vulkan1.1",
                        "-I" + str(pgs / "gs" / "shaders"),
                        "-I" + str(pgs / "Granite" / "assets" / "shaders" / "inc"),
                        *options, str(source), "-o", str(spv)], check=True)
        data = spv.read_bytes()
    assert len(data) % 4 == 0 and data[:4] == bytes.fromhex("03022307"), "not SPIR-V"
    return [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]


def write_header(name, origin, words, extra=()):
    lines = ["// Generated by tools/pgs_shader.py from %s. Do not edit." % origin,
             "// SPDX-License-Identifier: LGPL-3.0+ (derived from paraLLEl-GS)",
             *extra,
             "#pragma once",
             "#include <stdint.h>",
             "static const uint32_t pgs_%s_spirv[] = {" % name]
    for i in range(0, len(words), 8):
        lines.append("\t" + ", ".join("0x%08xu" % w for w in words[i:i + 8]) + ",")
    lines.append("};")
    (SHADERS / ("pgs_%s.spv.h" % name)).write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("pgs_%s.spv.h: %d words" % (name, len(words)))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--glslang", required=True)
    parser.add_argument("--pgs", required=True, type=pathlib.Path)
    args = parser.parse_args()
    write_header("sample_circuit", "pgs_sample_circuit.frag (PROMOTED=0)",
                 compile_spirv(args.glslang, args.pgs, SHADERS / "pgs_sample_circuit.frag", ["-DPROMOTED=0"]))

    shaders = args.pgs / "gs" / "shaders"
    for name, changes in PATCHED.items():
        files = sources(shaders, name + ".comp")
        digest = hashlib.sha256("".join(read_source(shaders / f) for f in files).encode("utf-8")).hexdigest()
        source = read_source(shaders / (name + ".comp"))
        for before, after, count in changes:
            assert source.count(before) == count, "%s.comp does not match the pinned source" % name
            source = source.replace(before, after)
        # slangmosh, which builds the checkout's shaders, enables #include itself.
        source = source.replace("#version 450\n", "#version 450\n#extension GL_GOOGLE_include_directive : require\n", 1)
        with tempfile.TemporaryDirectory() as scratch:
            patched = pathlib.Path(scratch) / (name + ".comp")
            patched.write_text(source, encoding="utf-8", newline="\n")
            words = compile_spirv(args.glslang, args.pgs, patched, ["-Os", "-g0"])
        write_header(name, "the pinned %s.comp, with the menu smoothing change" % name, words,
                     ["// pgs-sources: " + " ".join(files), "// pgs-sha256: " + digest])


if __name__ == "__main__":
    main()
